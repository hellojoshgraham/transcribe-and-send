import Foundation
import CryptoKit

public enum TSError: LocalizedError, Equatable {
    case message(String)
    public var errorDescription: String? { if case let .message(value) = self { return value }; return nil }
}

public enum TailAddress {
    /// Deliberately accepts only literal Tailscale IPv4 addresses; no DNS, URL or LAN fallback.
    public static func isValid(_ value: String) -> Bool {
        let parts = value.split(separator: ".", omittingEmptySubsequences: false)
        guard parts.count == 4, parts.allSatisfy({ !$0.isEmpty && $0.allSatisfy({ $0.isASCII && $0.isNumber }) }),
              let a = UInt8(parts[0]), let b = UInt8(parts[1]), UInt8(parts[2]) != nil, UInt8(parts[3]) != nil,
              parts.allSatisfy({ String(UInt8($0)!) == $0 }) else { return false }
        return a == 100 && (64...127).contains(b)
    }
}

public struct PairingKey: Sendable {
    public let data: Data
    public init(encoded: String) throws {
        guard let data = Data(base64Encoded: encoded.trimmingCharacters(in: .whitespacesAndNewlines)), data.count == 32 else {
            throw TSError.message("Enter the pairing key generated by T&S on your receiving Mac.")
        }
        self.data = data
    }
    public init() { data = SymmetricKey(size: .bits256).withUnsafeBytes { Data($0) } }
    public var encoded: String { data.base64EncodedString() }
    public var fingerprint: String { SHA256.hash(data: data).prefix(6).map { String(format: "%02x", $0) }.joined(separator: ":") }
}

public struct WireMessage: Codable, Equatable, Sendable {
    public enum Kind: String, Codable, Sendable { case challenge, text, probe, receipt, preparePaste, prepared, paste, pasteReceipt, prepareImage, imagePrepared, image, imageReceipt }
    public var version: Int = 1
    public let kind: Kind
    public let challenge: UUID
    public let timestamp: Double
    public var text: String?
    public var digest: String?
    public var success: Bool?
    public var capabilities: [String]?
    public var requestID: UUID?
    public var pasteRequested: Bool?
    public var pasteOutcome: PasteOutcome?
    public var imageData: Data?
    public var contentType: String?

    public init(kind: Kind, challenge: UUID, text: String? = nil, digest: String? = nil, success: Bool? = nil, now: Date = Date()) {
        self.kind = kind; self.challenge = challenge; timestamp = now.timeIntervalSince1970
        self.text = text; self.digest = digest; self.success = success
    }

    public func validate(now: Date = Date()) throws {
        let imageKind = [.prepareImage, .imagePrepared, .image, .imageReceipt].contains(kind)
        guard version == (imageKind ? 2 : 1), timestamp.isFinite, abs(now.timeIntervalSince1970 - timestamp) <= 60 else {
            throw TSError.message("Connection expired or clocks differ. Check automatic date and time on both Macs.")
        }
        guard imageKind || (imageData == nil && contentType == nil) else { throw TSError.message("Unexpected image payload.") }
    }
}

public enum PasteOutcome: String, Codable, Sendable {
    case requested, disabled, permissionNeeded, focusUnavailable, focusChanged, senderFocusChanged, clipboardChanged, protectedInput, modifiersHeld, cancelled

    public var message: String {
        switch self {
        case .requested: return "Paste shortcut sent."
        case .disabled: return "Clipboard ready. Allow automatic paste in the receiver’s T&S settings."
        case .permissionNeeded: return "Clipboard ready. Enable T&S Accessibility on the receiving Mac."
        case .focusUnavailable: return "Clipboard ready. Select a text field and paste manually."
        case .focusChanged: return "Clipboard ready. Focus changed; paste manually."
        case .senderFocusChanged: return "Clipboard ready. Focus changed on the sending Mac; paste manually."
        case .clipboardChanged: return "Clipboard changed before paste. Automatic paste skipped."
        case .protectedInput: return "Clipboard ready. Protected input is active; paste manually."
        case .modifiersHeld: return "Clipboard ready. Release modifier keys and paste manually."
        case .cancelled: return "Automatic paste cancelled."
        }
    }
}

public enum WireCodec {
    public static let maxTextBytes = 256 * 1024
    public static let maxFrameBytes = 2 * 1024 * 1024
    public static let maxImageBytes = 16 * 1024 * 1024
    // Base64 PNG plus JSON/encryption overhead; permitted only after authenticated preparation.
    public static let maxImageFrameBytes = 24 * 1024 * 1024
    private static let context = Data("au.com.instantai.ts/v1".utf8)

    public static func digest(_ text: String) -> String { SHA256.hash(data: Data(text.utf8)).map { String(format: "%02x", $0) }.joined() }
    public static func imageDigest(_ png: Data) -> String { SHA256.hash(data: png).map { String(format: "%02x", $0) }.joined() }

    public static func validateText(_ text: String) throws {
        guard !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty, text.utf8.count <= maxTextBytes, !text.contains("\0") else {
            throw TSError.message("The transcript is empty, contains a null character, or exceeds 256 KB.")
        }
    }

    public static func seal(_ message: WireMessage, key: PairingKey, maximumBytes: Int = maxFrameBytes) throws -> Data {
        let box = try AES.GCM.seal(JSONEncoder().encode(message), using: SymmetricKey(data: key.data), authenticating: context)
        guard maximumBytes <= maxImageFrameBytes, let combined = box.combined, combined.count <= maximumBytes else { throw TSError.message("Message is too large.") }
        return combined
    }

    public static func open(_ bytes: Data, key: PairingKey, now: Date = Date(), maximumBytes: Int = maxFrameBytes) throws -> WireMessage {
        guard maximumBytes >= 28, maximumBytes <= maxImageFrameBytes, (28...maximumBytes).contains(bytes.count) else { throw TSError.message("Invalid message length.") }
        let data = try AES.GCM.open(AES.GCM.SealedBox(combined: bytes), using: SymmetricKey(data: key.data), authenticating: context)
        let message = try JSONDecoder().decode(WireMessage.self, from: data)
        try message.validate(now: now)
        return message
    }

    public static func frame(_ bytes: Data, maximumBytes: Int = maxFrameBytes) throws -> Data {
        guard maximumBytes >= 28, maximumBytes <= maxImageFrameBytes, (28...maximumBytes).contains(bytes.count) else { throw TSError.message("Invalid message length.") }
        var length = UInt32(bytes.count).bigEndian
        return withUnsafeBytes(of: &length) { Data($0) } + bytes
    }

    public static func frameLength(_ header: Data, maximumBytes: Int = maxFrameBytes) throws -> Int {
        guard header.count == 4 else { throw TSError.message("Invalid frame header.") }
        let length = header.reduce(0) { ($0 << 8) | Int($1) }
        guard maximumBytes >= 28, maximumBytes <= maxImageFrameBytes, (28...maximumBytes).contains(length) else { throw TSError.message("Invalid message length.") }
        return length
    }

    public static func verifyReceipt(_ receipt: WireMessage, challenge: UUID, text: String?) throws {
        guard receipt.kind == .receipt, receipt.challenge == challenge, receipt.success == true,
              receipt.digest == text.map(digest) else {
            throw TSError.message("The receiving Mac did not confirm this clipboard write.")
        }
    }

    public static func verifyImageReceipt(_ receipt: WireMessage, challenge: UUID, requestID: UUID, png: Data) throws {
        guard receipt.kind == .imageReceipt, receipt.version == 2, receipt.challenge == challenge,
              receipt.requestID == requestID, receipt.success == true, receipt.contentType == "public.png",
              receipt.digest == imageDigest(png) else {
            throw TSError.message("The receiving Mac did not confirm this screenshot clipboard write.")
        }
    }
}
